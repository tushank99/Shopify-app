package com.shopify.erp.orders;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import jakarta.persistence.Version;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.ArrayList;
import java.util.List;

@Entity
@Table(name = "sales_order")
public class SalesOrder {

    /** 24-hex id, generated by the application so it can go straight into the order.placed event. */
    @Id
    @Column(length = 24)
    private String id;

    @Column(name = "customer_id", nullable = false, length = 24)
    private String customerId;

    @Column(name = "idempotency_key", length = 64, unique = true)
    private String idempotencyKey;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private OrderStatus status = OrderStatus.CREATED;

    @Column(name = "failure_reason", length = 500)
    private String failureReason;

    @Column(nullable = false, length = 3)
    private String currency;

    @Column(name = "total_price", nullable = false, precision = 14, scale = 2)
    private BigDecimal totalPrice;

    @Version
    @Column(nullable = false)
    private long version;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt = Instant.now().truncatedTo(ChronoUnit.MICROS);

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt = createdAt;

    @OneToMany(mappedBy = "order", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("lineNo ASC")
    private List<SalesOrderLine> lines = new ArrayList<>();

    protected SalesOrder() {
        // JPA
    }

    public SalesOrder(String id, String customerId, String idempotencyKey, String currency) {
        this.id = id;
        this.customerId = customerId;
        this.idempotencyKey = idempotencyKey;
        this.currency = currency;
        this.totalPrice = BigDecimal.ZERO.setScale(2);
    }

    public void addLine(String sku, String productId, int quantity, BigDecimal unitPrice) {
        SalesOrderLine line = new SalesOrderLine(this, lines.size() + 1, sku, productId, quantity, unitPrice);
        lines.add(line);
        totalPrice = totalPrice.add(line.getLineTotal());
    }

    @PreUpdate
    void onUpdate() {
        updatedAt = Instant.now().truncatedTo(ChronoUnit.MICROS);
    }

    public void transitionTo(OrderStatus target) {
        if (!status.next().contains(target)) {
            throw new IllegalStateException("Order " + id + ": illegal transition " + status + " -> " + target);
        }
        status = target;
    }

    public void cancel(String reason) {
        transitionTo(OrderStatus.CANCELLED);
        failureReason = reason == null ? null : reason.substring(0, Math.min(reason.length(), 500));
    }

    public String getId() { return id; }
    public String getCustomerId() { return customerId; }
    public String getIdempotencyKey() { return idempotencyKey; }
    public OrderStatus getStatus() { return status; }
    public String getFailureReason() { return failureReason; }
    public String getCurrency() { return currency; }
    public BigDecimal getTotalPrice() { return totalPrice; }
    public Instant getCreatedAt() { return createdAt; }
    public List<SalesOrderLine> getLines() { return lines; }
}
